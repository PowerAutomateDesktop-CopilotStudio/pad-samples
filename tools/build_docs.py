def code_block(s):
    return [f"<details><summary>The code ({len(s.lines)} lines)</summary>", "",
            "```text", s.path.read_text(encoding="utf-8").rstrip(), "```", "", "</details>", ""]


def settings_table(s):
    """The first region of a subflow: the only values to change, with the comment the code gives them."""
    md = [f"The values to change are in the first region of `{s.name}` (cyan):", "",
          "| Variable | Value in the sample | What it is |", "|---|---|---|"]
    md += [f"| `{n}` | `{v}` | {d} |" if v else f"| `{n}` | *(empty)* | {d} |" for n, v, d in s.settings]
    return md + [""]


