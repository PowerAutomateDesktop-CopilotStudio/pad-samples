def released(sample):
    """The date of the current version, read from its CHANGELOG section '## x.y.z - YYYY-MM-DD'."""
    text = (sample.folder / "CHANGELOG.md").read_text(encoding="utf-8")
    m = re.search(rf"^## {re.escape(sample.version)} - (\d{{4}}-\d{{2}}-\d{{2}})", text, re.M)
    return m.group(1) if m else ""


def anchor(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


