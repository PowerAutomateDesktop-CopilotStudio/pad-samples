def catalogue(samples):
    """samples.json: the gallery as data, for search, filters or any other tool."""
    out = []
    for s in sorted(samples, key=lambda x: x.folder.name.lower()):
        c, first = s.card, s.ladder()[0]
        out.append({"id": c["id"], "title": c["title"], "summary": c["summary"], "category": c["category"], "kind": c["kind"],
                    "level": c["level"], "version": s.version, "released": released(s), "techniques": c["techniques"],
                    "requires": c.get("apps") or [], "quick_try_minutes": first["minutes"] if first["id"] == "quick" else None,
                    "setup_minutes": c["minutes"], "subflows": len(s.required), "inputs": s.n_in, "outputs": s.n_out,
                    "ui_elements": len(s.ui), "tested": c["tested"], "page": f"samples/{s.folder.name}/README.md"})
    return json.dumps({"samples": out}, indent=2, ensure_ascii=False, default=str) + "\n"


def techniques_page(samples, techniques):
    md = [GENERATED, "", "[All samples](README.md)", "", "# Samples by technique", "",
          "A technique is one reusable idea you can carry to another flow. Each sample lists the techniques it shows.", ""]
    for tid, t in techniques.items():
        users = [s for s in samples if tid in s.card["techniques"]]
        if not users:
            continue
        md += [f'<a id="{tid}"></a>', "", f"## {t['title']}", "", t["summary"], ""]
        md += [f"- [{s.card['title']}](samples/{s.folder.name}/README.md): {s.card['summary']}" for s in users]
        md.append("")
    return "\n".join(md)


def main():
    check = "--check" in sys.argv
    techniques = yaml.safe_load((ROOT / "techniques.yml").read_text(encoding="utf-8"))
    categories = yaml.safe_load((ROOT / "categories.yml").read_text(encoding="utf-8"))
    samples, failed, pages = [], False, {}
    for card_path in sorted((ROOT / "samples").glob("*/sample.yml"), key=lambda p: p.parent.name.lower()):
        folder = card_path.parent
        s = Sample(folder, yaml.safe_load(card_path.read_text(encoding="utf-8")), techniques)
        errors = s.errors()
        if s.card.get("category") not in categories:
            errors.append(f"category: '{s.card.get('category')}' is not in categories.yml ({', '.join(categories)})")
        for e in errors:
            print(f"FAIL {folder.name}: {e}")
        for w in s.warnings():
            print(f"WARN {folder.name}: {w}")
        if errors:
            failed = True
            continue
        pages[folder / "README.md"] = s.overview()
        pages[folder / "SETUP.md"] = s.setup()
        samples.append(s)
        print(f"ok   {folder.name}: {len(s.required)} subflow(s), {s.n_vars} variables, {len(s.ui)} UI elements")
    pages[ROOT / "README.md"] = gallery(samples, techniques, categories)
    pages[ROOT / "samples.json"] = catalogue(samples)
    pages[ROOT / "TECHNIQUES.md"] = techniques_page(samples, techniques)
    for path, text in pages.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"FAIL {path.relative_to(ROOT).as_posix()} is stale, run tools/build_docs.py")
                failed = True
        elif not failed:
            path.write_text(text, encoding="utf-8")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
