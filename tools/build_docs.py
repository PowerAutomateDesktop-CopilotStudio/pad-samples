"""build_docs.py - writes the pages of every sample, the gallery and the index by technique.

    python tools/build_docs.py            # write the pages
    python tools/build_docs.py --check    # fail (exit 1) when a page is stale or a card disagrees with its code

For each samples/<id>/, from sample.yml and flow/:
  README.md  the overview, for a consultant who decides in a minute: problem, solution, contract, how it works,
             design choices, performance, limits, files, tested versions
  SETUP.md   the step-by-step setup: files, subflows, variables, paste, run, adapt, troubleshooting
At the root: README.md (the gallery, categories in categories.yml), TECHNIQUES.md (samples by technique, vocabulary
in techniques.yml) and samples.json (the catalogue as data).

What is read from the code, never typed by hand:
  subflows and their scope (file name N-Name.txt, header '# local subflow:'), the contract (inputs / outputs),
  flow input / output variables (in_glob_ / out_glob_), UI elements (the ControlRepository block), line counts,
  the CALL line of the example, the settings (SET lines of the first region), the regions (diagram and steps).
"""
